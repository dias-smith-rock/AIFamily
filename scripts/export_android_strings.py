#!/usr/bin/env python3
"""Export localization/keys.json + iOS String Catalogs → Android strings.xml.

Usage:
  python3 scripts/export_android_strings.py
  python3 scripts/export_android_strings.py --tables Common,Auth,Schedule
"""

from __future__ import annotations

import argparse
import json
import re
import xml.sax.saxutils as xml
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEYS_PATH = ROOT / "localization" / "keys.json"
IOS_LOC_DIR = ROOT / "reminder" / "Localization"
ANDROID_RES = ROOT / "android" / "app" / "src" / "main" / "res"

# iOS locale → Android values folder
LOCALE_DIR = {
    "en": "values",
    "zh-Hans": "values-zh-rCN",
    "zh-Hant": "values-zh-rTW",
    "es": "values-es",
    "fr": "values-fr",
    "pt": "values-pt",
    "ar": "values-ar",
    "hi": "values-hi",
    "ta": "values-ta",
}

# Always merge into default `values` (UI bootstrap + app label)
BOOTSTRAP_KEYS = {
    "app_name": "Family Link",
    "common_schedule": "Schedule",
    "common_to_dos": "To-Dos",
    "common_location": "Location",
    "common_wallet": "Wallet",
    "common_settings_tab": "Settings",
    "common_loading": "Loading…",
    "common_reload": "Reload",
    "common_save": "Save",
    "common_done": "Done",
    "auth_sign_in_with_email": "Sign in with email",
    "auth_sign_in_with_google": "Sign in with Google",
    "auth_continue_as_guest": "Continue as guest",
    "family_create_group": "Create group",
    "family_join_group": "Join group",
    "family_group_locations": "Group locations",
    "schedule_loading_tasks": "Loading tasks…",
    "schedule_empty_new_task": "New task",
    "billing_restore_purchases": "Restore purchases",
    "billing_subscribe_pro": "Subscribe to Pro",
    "location_hide_location": "Hide location",
}


def ios_to_android_format(value: str) -> str:
    """Convert common iOS format tokens to Android."""
    out = value
    # Positional / simple replacements
    out = out.replace("%@", "%s")
    out = out.replace("%lld", "%d")
    out = out.replace("%ld", "%d")
    # iOS positional %1$@ → %1$s
    out = re.sub(r"%(\d+)\$@", r"%\1$s", out)
    out = re.sub(r"%(\d+)\$lld", r"%\1$d", out)
    out = re.sub(r"%(\d+)\$ld", r"%\1$d", out)
    # Escape Android specials for string resources (after format convert)
    out = out.replace("'", r"\'")
    out = out.replace("&", "&amp;")
    # Keep < > as entities if present as literal text
    out = out.replace("<", "&lt;").replace(">", "&gt;")
    return out


def load_catalog(table: str) -> dict:
    path = IOS_LOC_DIR / f"{table}.xcstrings"
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return data.get("strings") or {}


def android_name(key: str) -> str:
    # Android resource names: [a-z0-9_]
    name = re.sub(r"[^a-zA-Z0-9_]", "_", key)
    if name and name[0].isdigit():
        name = "k_" + name
    return name.lower()


def write_strings_xml(folder: Path, entries: dict[str, str]) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<resources>",
        "    <!-- Generated by scripts/export_android_strings.py — do not hand-edit -->",
        "    <!-- App bootstrap keys live in strings_app.xml -->",
    ]
    for name in sorted(entries.keys()):
        lines.append(f'    <string name="{name}">{entries[name]}</string>')
    lines.append("</resources>")
    lines.append("")
    # Keep generated catalog separate from strings_app.xml bootstrap keys.
    (folder / "strings_generated.xml").write_text("\n".join(lines), encoding="utf-8")
    # Remove legacy overwrite target if present from early runs.
    legacy = folder / "strings.xml"
    if legacy.exists() and "Generated by scripts/export_android_strings.py" in legacy.read_text(encoding="utf-8"):
        legacy.unlink()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--tables",
        default="Common,Auth,Schedule,Family,Settings,Location,VIP",
        help="Comma-separated catalog tables to export",
    )
    args = parser.parse_args()
    tables = [t.strip() for t in args.tables.split(",") if t.strip()]

    keys = json.loads(KEYS_PATH.read_text(encoding="utf-8"))
    wanted = {
        row["new_key"]: row["table"]
        for row in keys
        if row.get("new_key") and row.get("table") in tables and not row.get("orphan", False)
    }

    catalogs = {table: load_catalog(table) for table in tables}

    # locale → { android_name → value }
    by_locale: dict[str, dict[str, str]] = defaultdict(dict)

    for key, table in wanted.items():
        catalog = catalogs.get(table) or {}
        entry = catalog.get(key) or {}
        locs = entry.get("localizations") or {}
        name = android_name(key)
        for locale, folder in LOCALE_DIR.items():
            unit = (locs.get(locale) or {}).get("stringUnit") or {}
            value = unit.get("value")
            if not value:
                # Fall back to English for missing translations
                en_unit = (locs.get("en") or {}).get("stringUnit") or {}
                value = en_unit.get("value")
            if not value:
                # Last resort: legacy_key from keys.json or the key itself
                continue
            by_locale[folder][name] = ios_to_android_format(value)

    # Bootstrap defaults (do not override catalog translations already present)
    for name, value in BOOTSTRAP_KEYS.items():
        by_locale["values"].setdefault(name, ios_to_android_format(value))

    if not ANDROID_RES.exists():
        raise SystemExit(f"Android res dir missing: {ANDROID_RES}")

    for folder_name, entries in sorted(by_locale.items()):
        write_strings_xml(ANDROID_RES / folder_name, entries)
        print(f"Wrote {len(entries):4d} strings → {folder_name}/strings_generated.xml")

    # Marker for shared/i18n
    marker = ROOT / "shared" / "i18n" / "README.md"
    marker.parent.mkdir(parents=True, exist_ok=True)
    marker.write_text(
        "# Android i18n export\n\n"
        "Generated resources live under `android/app/src/main/res/values*/strings.xml`.\n"
        "Run `python3 scripts/export_android_strings.py` after updating `localization/keys.json` "
        "or iOS catalogs.\n",
        encoding="utf-8",
    )
    print("Done.")


if __name__ == "__main__":
    main()
