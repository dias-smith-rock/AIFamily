def make_entry(translations: dict[str, str]) -> dict:
    return {
        "localizations": {
            locale: {"stringUnit": {"state": "translated", "value": translations[locale]}}
            for locale in LOCALES
        }
    }


def main() -> None:
    data = json.loads(XCSTRINGS_PATH.read_text(encoding="utf-8"))
    strings = data.setdefault("strings", {})
    for key, translations in LOCATION_KEYS.items():
        strings[key] = make_entry(translations)
    XCSTRINGS_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Updated {len(LOCATION_KEYS)} location keys in {XCSTRINGS_PATH}")


if __name__ == "__main__":
    main()
